def _run_cli(
    tmp_path: Path, args: list[str], *, env: dict[str, str] | None = None
) -> subprocess.CompletedProcess[str]:
    """Run the memoryledger CLI as a subprocess in tmp_path."""
    env_vars = dict(os.environ)
    env_vars.pop("MEMORYLEDGER_ACTOR", None)
    env_vars.pop("MEMORYLEDGER_NOW", None)
    env_vars.update(env or {})
    env_vars["MEMORYLEDGER_NOW"] = "2026-06-13T10:00:00+02:00"
    result = subprocess.run(
        ["memoryledger", *args],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        env=env_vars,
    )
    return result


def test_entrypoint_alias_memledger(tmp_path: Path) -> None:
    """Both memoryledger and memledger console_scripts invoke the Typer app."""
    # Set up a project.
    result = _run_cli(tmp_path, ["init"])
    assert result.returncode == 0, f"init failed: {result.stderr}"
    note = tmp_path / "note.md"
    note.write_text("Run pytest.\n")
    result = _run_cli(
        tmp_path,
        ["capture", "--type", "procedural", "--title", "Test", "--body", str(note)],
    )
    assert result.returncode == 0, f"capture failed: {result.stderr}"

    # Now test memledger alias.
    result2 = subprocess.run(
        ["memledger", "list"],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        env={**os.environ, "MEMORYLEDGER_NOW": "2026-06-13T10:00:00+02:00"},
    )
    assert result2.returncode == 0, f"memledger list failed: {result2.stderr}"
    assert "mem-20260613-0001" in result2.stdout


def test_doctor_creates_export_dir(tmp_path: Path) -> None:
    """doctor creates the export directory if missing and create_export_dir=True."""
    store = init_store(tmp_path, now=FIXED_NOW)
    # Remove the export dir.
    import shutil

    if store.exports_dir.exists():
        shutil.rmtree(store.exports_dir)
    assert not store.exports_dir.exists()
    report = store.diagnose(create_export_dir=True)
    assert store.exports_dir.exists(), "doctor should create missing export dir"
    assert report.export_dir_created
    assert report.export_dir_ok
